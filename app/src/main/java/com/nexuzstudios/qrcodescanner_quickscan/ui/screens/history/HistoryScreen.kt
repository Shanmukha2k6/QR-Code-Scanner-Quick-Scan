@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun HistoryScreen(viewModel: HistoryViewModel = hiltViewModel()) {
    val activeTab by viewModel.activeTab.collectAsState()
    val filter by viewModel.filter.collectAsState()
    val scans by viewModel.displayedScans.collectAsState()
    val generated by viewModel.displayedGenerated.collectAsState()
    val context = LocalContext.current
    var showClearDialog by remember { mutableStateOf(false) }
    var searchQuery by remember { mutableStateOf("") }
    var showSearch by remember { mutableStateOf(false) }
    var selectedGeneratedQR by remember { mutableStateOf<GeneratedQR?>(null) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("History", fontWeight = FontWeight.SemiBold) },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.background,
                    titleContentColor = MaterialTheme.colorScheme.onBackground
                ),
                actions = {
                    IconButton(onClick = { showSearch = !showSearch; if (!showSearch) searchQuery = "" }) {
                        Icon(
                            if (showSearch) Icons.Filled.SearchOff else Icons.Outlined.Search,
                            "Search",
                            tint = MaterialTheme.colorScheme.primary
                        )
                    }
                    IconButton(onClick = { showClearDialog = true }) {
                        Icon(
                            Icons.Outlined.DeleteSweep,
                            "Clear",
                            tint = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }
            )
        },
        containerColor = MaterialTheme.colorScheme.background
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(top = paddingValues.calculateTopPadding(), bottom = 0.dp)
        ) {
            // ── Search Bar ──────────────────────────────────────────────────
            AnimatedVisibility(
                visible = showSearch,
                enter = expandVertically() + fadeIn(),
                exit = shrinkVertically() + fadeOut()
            ) {
                OutlinedTextField(
                    value = searchQuery,
                    onValueChange = { searchQuery = it },
                    placeholder = { Text("Search history…") },
                    leadingIcon = { Icon(Icons.Outlined.Search, null) },
                    trailingIcon = {
                        if (searchQuery.isNotEmpty()) {
                            IconButton(onClick = { searchQuery = "" }) {
                                Icon(Icons.Filled.Close, null, modifier = Modifier.size(18.dp))
                            }
                        }
                    },
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 16.dp, vertical = 8.dp),
                    shape = RoundedCornerShape(12.dp),
                    singleLine = true
                )
            }

            // ── Tab Row ─────────────────────────────────────────────────────
            TabRow(
                selectedTabIndex = activeTab.ordinal,
                containerColor = MaterialTheme.colorScheme.background,
                contentColor = MaterialTheme.colorScheme.primary,
                indicator = { tabPositions ->
                    val pos = tabPositions[activeTab.ordinal]
                    TabRowDefaults.SecondaryIndicator(
                        modifier = Modifier
                            .fillMaxWidth()
                            .wrapContentSize(Alignment.BottomStart)
                            .offset(x = pos.left)
                            .width(pos.width),
                        color = MaterialTheme.colorScheme.primary
                    )
                }
            ) {
                Tab(
                    selected = activeTab == HistoryTab.SCANNED,
                    onClick = { viewModel.setTab(HistoryTab.SCANNED) },
                    text = { Text("Scanned", fontSize = 14.sp) },
                    selectedContentColor = MaterialTheme.colorScheme.primary,
                    unselectedContentColor = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Tab(
                    selected = activeTab == HistoryTab.GENERATED,
                    onClick = { viewModel.setTab(HistoryTab.GENERATED) },
                    text = { Text("Generated", fontSize = 14.sp) },
                    selectedContentColor = MaterialTheme.colorScheme.primary,
                    unselectedContentColor = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }

            // ── Filter Chips ────────────────────────────────────────────────
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 8.dp),
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                FilterChip(
                    onClick = { viewModel.setFilter(HistoryFilter.ALL) },
                    label = { Text("All") },
                    selected = filter == HistoryFilter.ALL,
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = MaterialTheme.colorScheme.primary,
                        selectedLabelColor = MaterialTheme.colorScheme.onPrimary
                    )
                )
                FilterChip(
                    onClick = { viewModel.setFilter(HistoryFilter.FAVORITES) },
                    label = { Text("⭐ Favorites") },
                    selected = filter == HistoryFilter.FAVORITES,
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = MaterialTheme.colorScheme.primary,
                        selectedLabelColor = MaterialTheme.colorScheme.onPrimary
                    )
                )
            }

            // ── Banner Ad ───────────────────────────────────────────────────
            BannerAdView(
                adUnitId = AdManager.BANNER_HISTORY_ID,
                modifier = Modifier.fillMaxWidth()
            )

            // ── Content ─────────────────────────────────────────────────────
            if (activeTab == HistoryTab.SCANNED) {
                val filtered = scans.filter {
                    searchQuery.isBlank() || it.rawValue.contains(searchQuery, ignoreCase = true)
                }
                if (filtered.isEmpty()) {
                    EmptyState(
                        if (searchQuery.isNotBlank()) "No results for \"$searchQuery\""
                        else "No scan history yet.\nStart scanning QR codes!"
                    )
                } else {
                    LazyColumn(
                        contentPadding = PaddingValues(16.dp),
                        verticalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        itemsIndexed(filtered, key = { _, item -> item.id }) { index, scan ->
                            AnimatedHistoryItem(index = index) {
                                val dismissState = rememberSwipeToDismissBoxState(
                                    confirmValueChange = { value ->
                                        if (value == SwipeToDismissBoxValue.EndToStart) {
                                            viewModel.deleteScan(scan)
                                            true
                                        } else false
                                    }
                                )
                                SwipeToDismissBox(
                                    state = dismissState,
                                    backgroundContent = {
                                        Box(
                                            modifier = Modifier
                                                .fillMaxSize()
                                                .clip(RoundedCornerShape(12.dp))
                                                .background(MaterialTheme.colorScheme.error)
                                                .padding(horizontal = 20.dp),
                                            contentAlignment = Alignment.CenterEnd
                                        ) {
                                            Icon(Icons.Outlined.Delete, null, tint = MaterialTheme.colorScheme.onError)
                                        }
                                    },
                                    enableDismissFromStartToEnd = false
                                ) {
                                    ScanHistoryItem(
                                        scan = scan,
                                        onCopy = { ClipboardUtil.copyToClipboard(context, scan.rawValue) },
                                        onShare = { ShareUtil.shareText(context, scan.rawValue) },
                                        onFavorite = { viewModel.toggleScanFavorite(scan) }
                                    )
                                }
                            }
                        }
                    }
                }
            } else {
                val filtered = generated.filter {
                    searchQuery.isBlank() || it.content.contains(searchQuery, ignoreCase = true) ||
                            it.title.contains(searchQuery, ignoreCase = true)
                }
                if (filtered.isEmpty()) {
                    EmptyState(
                        if (searchQuery.isNotBlank()) "No results for \"$searchQuery\""
                        else "No generated QR codes.\nCreate your first one!"
                    )
                } else {
                    LazyColumn(
                        contentPadding = PaddingValues(16.dp),
                        verticalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        itemsIndexed(filtered, key = { _, item -> item.id }) { index, qr ->
                            AnimatedHistoryItem(index = index) {
                                val dismissState = rememberSwipeToDismissBoxState(
                                    confirmValueChange = { value ->
                                        if (value == SwipeToDismissBoxValue.EndToStart) {
                                            viewModel.deleteGenerated(qr)
                                            true
                                        } else false
                                    }
                                )
                                SwipeToDismissBox(
                                    state = dismissState,
                                    backgroundContent = {
                                        Box(
                                            modifier = Modifier
                                                .fillMaxSize()
                                                .clip(RoundedCornerShape(12.dp))
                                                .background(MaterialTheme.colorScheme.error)
                                                .padding(horizontal = 20.dp),
                                            contentAlignment = Alignment.CenterEnd
                                        ) {
                                            Icon(Icons.Outlined.Delete, null, tint = MaterialTheme.colorScheme.onError)
                                        }
                                    },
                                    enableDismissFromStartToEnd = false
                                ) {
                                    GeneratedHistoryItem(
                                        qr = qr,
                                        onCopy = { ClipboardUtil.copyToClipboard(context, qr.content) },
                                        onShare = { ShareUtil.shareText(context, qr.content) },
                                        onFavorite = { viewModel.toggleGeneratedFavorite(qr) },
                                        onClick = { selectedGeneratedQR = qr }
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }

        if (showClearDialog) {
            AlertDialog(
                onDismissRequest = { showClearDialog = false },
                title = { Text("Clear History") },
                text = { Text("Delete all ${if (activeTab == HistoryTab.SCANNED) "scan" else "generated"} history?") },
                confirmButton = {
                    TextButton(onClick = {
                        if (activeTab == HistoryTab.SCANNED) viewModel.clearAllScans()
                        else viewModel.clearAllGenerated()
                        showClearDialog = false
                    }) { Text("Delete", color = MaterialTheme.colorScheme.error) }
                },
                dismissButton = {
                    TextButton(onClick = { showClearDialog = false }) { Text("Cancel") }
                }
            )
        }

        selectedGeneratedQR?.let { qr ->
            GeneratedQRDetailDialog(
                qr = qr,
                onDismiss = { selectedGeneratedQR = null }
            )
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Animated wrapper for staggered list entrance
// ─────────────────────────────────────────────────────────────────────────────

@Composable
private fun AnimatedHistoryItem(index: Int, content: @Composable () -> Unit) {
    var visible by remember { mutableStateOf(false) }
    LaunchedEffect(Unit) {
        kotlinx.coroutines.delay(index.toLong() * 40)
        visible = true
    }
    AnimatedVisibility(
        visible = visible,
        enter = fadeIn(tween(250)) + slideInVertically(
            initialOffsetY = { it / 4 },
            animationSpec = tween(300, easing = FastOutSlowInEasing)
        )
    ) {
        content()
    }
}

